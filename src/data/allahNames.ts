export function parseQuranRefs(found: string): { surah: number; ayah: number }[] {
  const refs: { surah: number; ayah: number }[] = [];
  const regex = /\((\d+)[:\s](\d+)\)/g;
  let match;
  while ((match = regex.exec(found)) !== null) {
    refs.push({ surah: parseInt(match[1], 10), ayah: parseInt(match[2], 10) });
  }
  return refs;
}